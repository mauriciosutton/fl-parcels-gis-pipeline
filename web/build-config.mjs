// Writes web/config.js from environment variables, for hosts that build from the repository (Vercel).
//   MAPBOX_TOKEN   public "pk." token for the basemap (optional: without it the map has no basemap)
//   PMTILES_URL    absolute https URL of the parcels .pmtiles (required)
//   DEFAULT_BASEMAP  "satellite" | "streets" | "light" | "none" (optional)
// Everything written here is visible to every visitor, so a secret ("sk.") token is refused.
import { writeFileSync } from "node:fs";

const fail = (message) => {
  console.error(`build-config: ${message}`);
  process.exit(1);
};

const token = (process.env.MAPBOX_TOKEN ?? "").trim();
const url = (process.env.PMTILES_URL ?? "").trim();
const basemap = (process.env.DEFAULT_BASEMAP ?? "satellite").trim();

if (token && !token.startsWith("pk.")) fail("MAPBOX_TOKEN must be a public token starting with 'pk.'; never use a secret 'sk.' token");
if (!url) fail("PMTILES_URL is not set (the public URL of the .pmtiles file)");
if (!/^https:\/\//.test(url)) fail(`PMTILES_URL must be an absolute https:// URL, got ${JSON.stringify(url)}`);
if (!["satellite", "streets", "light", "none"].includes(basemap)) fail(`DEFAULT_BASEMAP ${JSON.stringify(basemap)} is not one of satellite, streets, light, none`);
if (!token) console.warn("build-config: MAPBOX_TOKEN is not set; the map will render without a basemap");

const config = {
  MAPBOX_TOKEN: token,
  PMTILES_URL: url,
  INITIAL_VIEW: { center: [-80.62, 28.08], zoom: 14 },
  DEFAULT_BASEMAP: basemap,
};

const out = new URL("./config.js", import.meta.url);
writeFileSync(out, `// Generated by build-config.mjs from environment variables. Do not edit or commit.\nwindow.CONFIG = ${JSON.stringify(config, null, 2)};\n`);
console.log(`build-config: wrote web/config.js (token ${token ? "set" : "not set"}, tiles ${url})`);
